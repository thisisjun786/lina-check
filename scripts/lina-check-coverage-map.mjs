#!/usr/bin/env node

/**
 * Definition: generate and verify the record-by-record coverage map for the
 * excluded upstream suites.
 *
 * The map is a claim about two sets of files: every test record the ten excluded
 * suites declare, and every record the derived suites restore. A committed table
 * that nothing regenerates goes stale the first time either set changes, and the
 * staleness is invisible because the document still reads correctly. So the
 * table and its receipt are outputs of this module, and lina:contract-selftest
 * runs it in check mode, where any drift from the committed files fails.
 *
 * Two rules keep the map honest in both directions. A record the derived suites
 * do not restore must carry a written reason here, or generation fails. A record
 * that carries a reason but is restored anyway also fails, because a stale reason
 * would understate the recovery just as badly as a missing row overstates it.
 *
 * Usage: node scripts/lina-check-coverage-map.mjs <write|check>
 */

