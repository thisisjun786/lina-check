export function generate(readFile = (path) => readFileSync(join(root, path), "utf8")) {
  const receipt = summarise(buildRecords(readFile));
  return { receipt, json: JSON.stringify(receipt, null, 2) + "\n", table: renderTable(receipt) };
}

export function main(argv, readFile) {
  const mode = argv[0];
  if (mode !== "write" && mode !== "check") {
    process.stderr.write("usage: node scripts/lina-check-coverage-map.mjs <write|check>\n");
    return 2;
  }
  const { receipt, json, table } = generate(readFile);
  if (mode === "write") {
    writeFileSync(join(root, RECEIPT), json);
    writeFileSync(join(root, TABLE), table);
    process.stdout.write(
      LABEL + " wrote " + receipt.total_records + " records to " + TABLE + " and " + RECEIPT + "\n",
    );
    return 0;
  }
  const drifted = [
    [RECEIPT, json],
    [TABLE, table],
  ].filter(([path, expected]) => readFileSync(join(root, path), "utf8") !== expected);
  if (drifted.length > 0) {
    process.stderr.write(
      LABEL + " stale: " + drifted.map(([path]) => path).join(", ") +
        "; regenerate with: node scripts/lina-check-coverage-map.mjs write\n",
    );
    return 1;
  }
  process.stdout.write(
    LABEL + " current: " + receipt.total_records + " records, " + receipt.counts.recovered +
      " recovered, " + receipt.counts.partial + " partial, " + receipt.counts.lost + " lost\n",
  );
  return 0;
}

if (process.argv[1] && process.argv[1].endsWith("lina-check-coverage-map.mjs"))
  process.exitCode = main(process.argv.slice(2));
