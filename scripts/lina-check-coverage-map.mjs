/**
 * Blank out comments, respecting string and template literals.
 *
 * A line-by-line scan counted a declaration inside a block comment as a record
 * and missed one whose name sits on the next line. Both directions are wrong in
 * the same way: the map would stay green while the executed record set changed.
 * Naive comment stripping is not enough either, since "https://x" carries the
 * line-comment marker inside a string.
 */
export function stripComments(source) {
  let out = "";
  let index = 0;
  let quote = null;
  while (index < source.length) {
    const two = source.slice(index, index + 2);
    const character = source[index];
    if (quote) {
      if (character === "\\") {
        out += "  ";
        index += 2;
        continue;
      }
      if (character === quote) quote = null;
      out += character;
      index += 1;
      continue;
    }
    if (character === '"' || character === "'" || character === BT) {
      quote = character;
      out += character;
      index += 1;
      continue;
    }
    if (two === "//") {
      while (index < source.length && source[index] !== "\n") {
        out += " ";
        index += 1;
      }
      continue;
    }
    if (two === "/*") {
      while (index < source.length && source.slice(index, index + 2) !== "*/") {
        out += source[index] === "\n" ? "\n" : " ";
        index += 1;
      }
      out += "  ";
      index += 2;
      continue;
    }
    out += character;
    index += 1;
  }
  return out;
}

const TEST_DECLARATION = new RegExp(
  "(?:^|[\\s;{}()])(?:await\\s+)?(?:test|nodeTest)(\\.(?:skip|todo|only))?\\s*\\(\\s*([\"'" +
    BT +
    "])((?:[^\\\\]|\\\\.)*?)\\2\\s*(?:,\\s*(\\{[^}]*\\}))?",
  "gm",
);

function expand(raw) {
  if (raw.includes(NAME_SLOT) && raw.includes(STATUS_SLOT))
    return READERS.flatMap((reader) =>
      STATUSES.map((status) => raw.replace(NAME_SLOT, reader).replace(STATUS_SLOT, String(status))),
    );
  if (raw.includes(NAME_SLOT)) return READERS.map((reader) => raw.replace(NAME_SLOT, reader));
  return [raw];
}

/**
 * Declared records, with the parameterised suites expanded to what runs.
 *
 * skipped is read from the options argument, because a name alone cannot tell a
 * case that runs from one declared with { skip: true }. Treating those as equal
 * would let the map certify coverage that never executes.
 */
export function declarations(source) {
  const found = [];
  for (const match of stripComments(source).matchAll(TEST_DECLARATION)) {
    // Two ways a case can be declared without running: the member form
    // test.skip(...) and an options object. The options form has to read the
    // value, because { skip: false } is a case that runs and an earlier version
    // recorded it as skipped.
    const member = match[1] ?? "";
    const options = match[4] ?? "";
    const flagged = /\b(?:skip|todo)\s*:\s*(?!false\b)[A-Za-z0-9_."'\u0060]/.test(options);
    const skipped = member === ".skip" || member === ".todo" || flagged;
    for (const name of expand(match[3])) found.push({ name, skipped });
  }
  return found;
}

/** Every declared record name, whether or not it executes. */
export function testNames(source) {
  return declarations(source).map((entry) => entry.name);
}

/** Only the records that actually run, which is what "restored" has to mean. */
export function executedNames(source) {
  return declarations(source)
    .filter((entry) => !entry.skipped)
    .map((entry) => entry.name);
}

export function buildRecords(readFile) {
  const records = [];
  for (const [original, derived] of Object.entries(RECOVERY)) {
    const restored = new Set(executedNames(readFile(derived)));
    const declared = [
      ...testNames(readFile(original)).map((name) => ({ name, nested: false })),
      ...(NESTED[original] ?? []).map((entry) => ({
        name: entry.parent + " > " + entry.name,
        nested: true,
      })),
    ];
    for (const entry of declared) {
      const recorded = (UNRESTORED[original] ?? {})[entry.name];
      if (restored.has(entry.name)) {
        if (recorded)
          throw new Error(
            "recorded as unrestored but restored by name: " + original + " :: " + entry.name,
          );
        records.push({
          original,
          case: entry.name,
          nested: entry.nested,
          disposition: "recovered",
          covered_by: derived,
          note: "",
        });
        continue;
      }
      if (!recorded)
        throw new Error("no disposition recorded for: " + original + " :: " + entry.name);
      records.push({
        original,
        case: entry.name,
        nested: entry.nested,
        disposition: recorded[0],
        covered_by: recorded[0] === "partial" ? derived : "",
        note: recorded[1],
      });
    }
  }
  return records;
}

export function summarise(records) {
  const counts = { recovered: 0, partial: 0, lost: 0 };
  const perFile = {};
  const seen = new Set();
  const duplicates = [];
  for (const record of records) {
    counts[record.disposition] += 1;
    perFile[record.original] ??= { total: 0, recovered: 0, partial: 0, lost: 0 };
    perFile[record.original].total += 1;
    perFile[record.original][record.disposition] += 1;
    const key = record.original + " :: " + record.case;
    if (seen.has(key)) duplicates.push(key);
    seen.add(key);
  }
  return {
    generated_for: "LINA-1 (JUN-223)",
    total_records: records.length,
    top_level_records: records.filter((record) => !record.nested).length,
    nested_records: records.filter((record) => record.nested).length,
    distinct_case_ids: seen.size,
    duplicate_case_ids: duplicates,
    counts,
    per_file: perFile,
    records,
  };
}

